export type IconName = keyof typeof ICON_REGISTRY | (string & {});

/**
 * Resolves an icon name or component reference into an IconDescriptor
 */
export function getIconDescriptor(
  nameOrComponent?: IconName | LucideIcon | ComponentType<any> | null
): IconDescriptor | null {
  if (!nameOrComponent) return null;

  if (typeof nameOrComponent === 'string') {
    const desc = ICON_REGISTRY[nameOrComponent];
    if (desc) return desc;
    // Fallback: try kebab-case
    const kebab = nameOrComponent.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
    if (ICON_REGISTRY[kebab]) return ICON_REGISTRY[kebab];
    // Unknown name fallback
    return null;
  }

  // If a direct component was passed (e.g. for backward compatibility)
  for (const key in ICON_REGISTRY) {
    if (ICON_REGISTRY[key].Static === nameOrComponent) {
      return ICON_REGISTRY[key];
    }
  }

  return {
    Static: nameOrComponent as LucideIcon,
    defaultBehavior: 'static',
    name: 'custom',
  };
}
