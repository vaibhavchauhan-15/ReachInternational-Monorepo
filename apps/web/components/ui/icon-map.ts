export type IconName = keyof typeof ICONS;

/**
 * Resolves an icon name or string to a LucideIcon component.
 * Performs direct lookup and falls back to normalized case-insensitive comparison.
 */
export function getIcon(name: string | null | undefined): LucideIcon | null {
  if (!name) return null;
  if (name in ICONS) {
    return ICONS[name as IconName];
  }

  // Fallback normalization: strip dashes, underscores, and whitespace
  const normalized = name.toLowerCase().replace(/[-_\s]/g, "");
  for (const [key, icon] of Object.entries(ICONS)) {
    if (key.toLowerCase().replace(/[-_\s]/g, "") === normalized) {
      return icon as LucideIcon;
    }
  }

  return null;
}
