export function exportClientsToExcel(
  clients: (CRMClient | ClientExportRecord)[],
  filenamePrefix: string = "Client-Directory"
) {
  if (!clients || clients.length === 0) return;

  const { displayDateTime } = formatExportDateTimeSlug();
  const normalized = clients.map(normalizeClientForExport);

  const titleRow = ["REACH INTERNATIONAL — CLIENT DIRECTORY REPORT"];
  const metaRow = [
    `Total Clients Exported: ${clients.length}`,
    `Export Date: ${displayDateTime}`,
    `Generated By: ReachInternational Client Operations`,
  ];
  const blankRow = [""];

  let activeCount = 0;
  let inactiveCount = 0;

  const dataRows = normalized.map((item, index) => {
    if (item.status === "ACTIVE") activeCount++;
    else inactiveCount++;

    return [
      index + 1,
      item.clientId,
      item.companyName,
      item.contactPerson,
      item.phone,
      item.gstin,
      item.pan,
      item.siteAddress,
      item.city,
      item.district,
      item.state,
      item.pincode,
      item.isBillingDiff ? "Yes" : "No",
      item.billingAddress,
      item.status,
      item.createdAt,
    ];
  });

  const summaryRow = [
    `TOTAL: ${clients.length} Clients | Active: ${activeCount} | Inactive / Soft-Deleted: ${inactiveCount}`,
  ];

  const worksheetData = [
    titleRow,
    metaRow,
    blankRow,
    CLIENT_EXPORT_COLUMNS,
    ...dataRows,
    blankRow,
    summaryRow,
  ];

  const worksheet = XLSX.utils.aoa_to_sheet(worksheetData);

  worksheet["!cols"] = [
    { wch: 8 },  // S.No
    { wch: 16 }, // Client ID
    { wch: 30 }, // Company Name
    { wch: 22 }, // Contact Person
    { wch: 18 }, // Phone
    { wch: 18 }, // GSTIN
    { wch: 15 }, // PAN
    { wch: 36 }, // Site Address
    { wch: 16 }, // City
    { wch: 16 }, // District
    { wch: 16 }, // State
    { wch: 12 }, // Pincode
    { wch: 16 }, // Separate Billing
    { wch: 36 }, // Billing Address
    { wch: 16 }, // Status
    { wch: 18 }, // Registration Date
  ];

  const workbook = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(workbook, worksheet, "Client Directory");

  const fileName = buildClientsExportFileName(filenamePrefix, "xlsx");
  XLSX.writeFile(workbook, fileName);
}

export function exportClientsToCSV(
  clients: (CRMClient | ClientExportRecord)[],
  filenamePrefix: string = "Client-Directory"
) {
  if (!clients || clients.length === 0) return;

  const normalized = clients.map(normalizeClientForExport);

  const escapeCSV = (value: string | number | null | undefined): string => {
    if (value === null || value === undefined) return '""';
    const str = String(value).replace(/"/g, '""');
    return `"${str}"`;
  };

  const rows = normalized.map((item, index) => [
    index + 1,
    item.clientId,
    item.companyName,
    item.contactPerson,
    item.phone,
    item.gstin,
    item.pan,
    item.siteAddress,
    item.city,
    item.district,
    item.state,
    item.pincode,
    item.isBillingDiff ? "Yes" : "No",
    item.billingAddress,
    item.status,
    item.createdAt,
  ]);

  const csvContent = [
    CLIENT_EXPORT_COLUMNS.map(escapeCSV).join(","),
    ...rows.map((row) => row.map(escapeCSV).join(",")),
  ].join("\r\n");

  const blob = new Blob(["\uFEFF" + csvContent], { type: "text/csv;charset=utf-8;" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  const fileName = buildClientsExportFileName(filenamePrefix, "csv");

  link.setAttribute("href", url);
  link.setAttribute("download", fileName);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

