export function exportClientsToPDF(
  clients: (CRMClient | ClientExportRecord)[],
  filenamePrefix: string = "Client-Directory",
  scopeLabel: string = "Full Directory"
) {
  if (!clients || clients.length === 0) return;

  const fileName = buildClientsExportFileName(filenamePrefix, "pdf");

  const styleId = "clients-pdf-print-styles";
  if (!document.getElementById(styleId)) {
    const styleEl = document.createElement("style");
    styleEl.id = styleId;
    styleEl.innerHTML = `
      @media screen {
        #${CLIENTS_PRINT_DOC_ID} {
          display: none !important;
        }
      }
      @media print {
        @page {
          size: landscape A4;
          margin: 6mm 8mm 6mm 8mm;
        }
        html, body {
          background: #ffffff !important;
          color: #000000 !important;
          height: auto !important;
          min-height: 0 !important;
          overflow: visible !important;
          position: static !important;
          margin: 0 !important;
          padding: 0 !important;
          -webkit-print-color-adjust: exact !important;
          print-color-adjust: exact !important;
        }
        body > *:not(#${CLIENTS_PRINT_DOC_ID}) {
          display: none !important;
        }
        #${CLIENTS_PRINT_DOC_ID} {
          display: block !important;
          position: static !important;
          width: 100% !important;
          margin: 0 !important;
          padding: 0 !important;
          visibility: visible !important;
        }
        #${CLIENTS_PRINT_DOC_ID} * {
          visibility: visible !important;
        }
      }
    `;
    document.head.appendChild(styleEl);
  }

  let container = document.getElementById(CLIENTS_PRINT_DOC_ID);
  if (!container) {
    container = document.createElement("div");
    container.id = CLIENTS_PRINT_DOC_ID;
    document.body.appendChild(container);
  }

  container.innerHTML = generateClientsReportHtml(clients, scopeLabel);

  handleBrowserPrint(fileName);
}
